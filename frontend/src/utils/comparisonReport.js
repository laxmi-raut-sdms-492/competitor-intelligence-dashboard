import { jsPDF } from 'jspdf';
import { autoTable } from 'jspdf-autotable';

// Helpers to read the /api/compare response safely
const companyName = (c) => c?.company || 'Unknown';
const list = (items) => (items && items.length ? items.join(', ') : '—');

const getParts = (result) => {
  const comparison = result?.comparison || {};
  return {
    target: result?.target || {},
    competitors: result?.competitors || [],
    services: comparison.service_comparison || {},
    tech: comparison.technology_comparison || {},
    recommendations: comparison.recommendations || [],
  };
};

const today = () => new Date().toLocaleDateString('en-IN', { day: 'numeric', month: 'short', year: 'numeric' });

// Plain-text summary for pasting into WhatsApp / Slack / email
export const buildSummaryText = (result) => {
  const { target, competitors, services, tech, recommendations } = getParts(result);
  const lines = [
    `Competitor Comparison — ${companyName(target)} (${today()})`,
    `Compared with: ${list(competitors.map(companyName))}`,
    '',
    'Services',
    `• Common: ${list(services.common_services)}`,
    `• Only we offer: ${list(services.unique_to_target)}`,
    `• Missing (competitors offer): ${list(services.missing_from_target)}`,
    '',
    'Technologies',
    `• Shared: ${list(tech.common_technologies)}`,
    `• Only we use: ${list(tech.unique_to_target)}`,
    `• Missing (competitors use): ${list(tech.missing_from_target)}`,
  ];
  if (recommendations.length) {
    lines.push('', 'Recommendations');
    recommendations.forEach((rec, i) => {
      const missing = rec.missing?.length ? ` (${rec.missing.join(', ')})` : '';
      lines.push(`${i + 1}. ${rec.title}${rec.priority ? ` [${rec.priority}]` : ''}: ${rec.description || rec.reason || ''}${missing}`);
    });
  }
  lines.push('', 'Generated by Competitor Intel');
  return lines.join('\n');
};

export const copySummaryToClipboard = async (result) => {
  const text = buildSummaryText(result);
  try {
    await navigator.clipboard.writeText(text);
    return true;
  } catch {
    // Fallback for browsers that block the Clipboard API
    const area = document.createElement('textarea');
    area.value = text;
    area.style.position = 'fixed';
    area.style.opacity = '0';
    document.body.appendChild(area);
    area.select();
    const ok = document.execCommand('copy');
    document.body.removeChild(area);
    return ok;
  }
};

export const downloadComparisonPdf = (result) => {
  const { target, competitors, services, tech, recommendations } = getParts(result);
  const doc = new jsPDF({ unit: 'pt', format: 'a4' });
  const margin = 40;
  const purple = [99, 102, 241];
  let y = margin;

  // Title
  doc.setFont('helvetica', 'bold').setFontSize(18).setTextColor(15, 23, 42);
  doc.text('Competitor Comparison Report', margin, y);
  y += 20;
  doc.setFont('helvetica', 'normal').setFontSize(10).setTextColor(100, 116, 139);
  doc.text(`Generated on ${today()} by Competitor Intel`, margin, y);
  y += 24;

  // Companies
  doc.setFontSize(11).setTextColor(15, 23, 42);
  doc.setFont('helvetica', 'bold').text('Your company:', margin, y);
  doc.setFont('helvetica', 'normal').text(`${companyName(target)}${target.url ? `  (${target.url})` : ''}`, margin + 85, y);
  y += 16;
  doc.setFont('helvetica', 'bold').text('Competitors:', margin, y);
  const compText = doc.splitTextToSize(list(competitors.map((c) => `${companyName(c)}${c.url ? ` (${c.url})` : ''}`)), 430);
  doc.setFont('helvetica', 'normal').text(compText, margin + 85, y);
  y += compText.length * 14 + 10;

  const section = (title, body) => {
    autoTable(doc, {
      startY: y,
      head: [[title, '']],
      body,
      theme: 'grid',
      margin: { left: margin, right: margin },
      headStyles: { fillColor: purple, textColor: 255, fontStyle: 'bold' },
      columnStyles: { 0: { cellWidth: 160, fontStyle: 'bold' } },
      styles: { fontSize: 10, cellPadding: 6, valign: 'top' },
    });
    y = doc.lastAutoTable.finalY + 18;
  };

  section('Services', [
    ['Common services', list(services.common_services)],
    ['Only you offer', list(services.unique_to_target)],
    ['Missing (competitors offer)', list(services.missing_from_target)],
  ]);

  section('Technologies', [
    ['Shared technologies', list(tech.common_technologies)],
    ['Only you use', list(tech.unique_to_target)],
    ['Missing (competitors use)', list(tech.missing_from_target)],
  ]);

  if (recommendations.length) {
    autoTable(doc, {
      startY: y,
      head: [['#', 'Recommendation', 'Priority', 'Details']],
      body: recommendations.map((rec, i) => [
        i + 1,
        rec.title || '',
        rec.priority || '',
        [rec.description, rec.reason, rec.missing?.length ? `Examples: ${rec.missing.join(', ')}` : '']
          .filter(Boolean).join('\n'),
      ]),
      theme: 'grid',
      margin: { left: margin, right: margin },
      headStyles: { fillColor: purple, textColor: 255, fontStyle: 'bold' },
      columnStyles: { 0: { cellWidth: 24 }, 1: { cellWidth: 140, fontStyle: 'bold' }, 2: { cellWidth: 60 } },
      styles: { fontSize: 10, cellPadding: 6, valign: 'top' },
    });
  }

  // Page numbers
  const pages = doc.getNumberOfPages();
  for (let i = 1; i <= pages; i += 1) {
    doc.setPage(i);
    doc.setFontSize(9).setTextColor(148, 163, 184);
    doc.text(`Page ${i} of ${pages}`, doc.internal.pageSize.getWidth() - margin, doc.internal.pageSize.getHeight() - 20, { align: 'right' });
  }

  const safeName = companyName(target).replace(/[^a-z0-9]+/gi, '-').replace(/^-|-$/g, '') || 'company';
  doc.save(`comparison-report-${safeName}-${new Date().toISOString().slice(0, 10)}.pdf`);
};
